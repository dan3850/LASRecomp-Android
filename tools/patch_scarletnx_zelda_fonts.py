#!/usr/bin/env python3
"""Backport scarletnx/ScarletNX@3692ba68 font fix to pinned 34853ee (ABI 12).

Modify only CMake font selection and license, never game code or SNX_ABI.
Refuse unexpected sources. --revert restores the shared Termux source cache.
"""
import argparse
import shutil
from pathlib import Path

S = "$"
DEP_OLD = """    # the shared fonts' stand-ins (cmake/shared_fonts.cmake), the two Eden carries: Open Sans 1.101 (Apache 2.0) from
    # Google's fonts repository, and yuzu's controller button glyphs (GPL-2.0-or-later) in the source file Eden keeps
    # them in. Single files, not archives"""
DEP_NEW = """    # Link's Awakening needs U+25A1: use DejaVu Sans 2.37 as upstream 3692ba68 does.
    # Keep the original controller glyphs; this is a font-only ABI 12 backport."""
CPM_OLD = """    CPMAddPackage(NAME OpenSans VERSION 1.101
                  URL https://raw.githubusercontent.com/google/fonts/4e24bf1805f1526cd1ce3e39447d5f8e6f1f6b67/apache/opensans/OpenSans-Regular.ttf
                  URL_HASH SHA256=13c03e22a633919beb2847c58c8285fb8a735ee97097d7c48fd403f8294b05f8
                  DOWNLOAD_ONLY YES DOWNLOAD_NO_EXTRACT YES)"""
CPM_NEW = """    CPMAddPackage(NAME DejaVuSans VERSION 2.37
                  URL https://github.com/dejavu-fonts/dejavu-fonts/releases/download/version_2_37/dejavu-fonts-ttf-2.37.tar.bz2
                  URL_HASH SHA256=fa9ca4d13871dd122f61258a80d01751d603b4d3ee14095d65453b4e846e17d7
                  DOWNLOAD_ONLY YES)"""

PATCHES = {
    "cmake/dependencies.cmake": [(DEP_OLD, DEP_NEW), (CPM_OLD, CPM_NEW)],
    "cmake/shared_fonts.cmake": [
        ("# fonts/ of its own): snx_font_standard, Open Sans 1.101, for every slot but FontNintendoExtended, and",
         "# fonts/ of its own): snx_font_standard, DejaVu Sans 2.37, for every slot but FontNintendoExtended, and"),
        ("# fetches both; the glyphs come as the C++ byte array Eden's source holds them in, so their bytes are read out of it",
         "# fetches both; DejaVu is a TTF and controller glyphs are read from Eden's C++ byte array"),
        ('file(GLOB snx_open_sans "' + S + '{OpenSans_SOURCE_DIR}/*.ttf")',
         'set(snx_dejavu "' + S + '{DejaVuSans_SOURCE_DIR}/ttf/DejaVuSans.ttf")'),
        ("if(NOT snx_open_sans OR NOT snx_oss_ext)",
         'if(NOT EXISTS "' + S + '{snx_dejavu}" OR NOT snx_oss_ext)'),
        ("The shared fonts' stand-ins are missing (" + S + "{OpenSans_SOURCE_DIR}, " + S + "{YuzuOSSExtension_SOURCE_DIR})",
         "The shared fonts' stand-ins are missing (" + S + "{snx_dejavu}, " + S + "{YuzuOSSExtension_SOURCE_DIR})"),
        ('file(READ "' + S + '{snx_open_sans}" snx_font_hex HEX)',
         'file(READ "' + S + '{snx_dejavu}" snx_font_hex HEX)'),
        ("Generated by cmake/shared_fonts.cmake from Open Sans 1.101 (Apache 2.0)",
         "Generated by cmake/shared_fonts.cmake from DejaVu Sans 2.37 (Bitstream Vera license)"),
    ],
    "CMakeLists.txt": [
        ("install(FILES dist/licenses/OpenSans/LICENSE DESTINATION " + S + "{licenses}/OpenSans) # the shared fonts' stand-in (pl.c)",
         "install(FILES dist/licenses/DejaVu/LICENSE DESTINATION " + S + "{licenses}/DejaVu) # the shared fonts' stand-in (pl.c)"),
    ],
}


def migrate(text, pairs, revert, path):
    for old, new in pairs:
        before, after = (new, old) if revert else (old, new)
        present, already = text.count(before), text.count(after)
        if present == 1 and already == 0:
            text = text.replace(before, after, 1)
        elif present == 0 and already == 1:
            pass
        else:
            raise ValueError(f"{path}: unknown font patch state at {before[:70]!r}")
    return text


def run(source: Path, license_file: Path, revert: bool):
    changed = {}
    for rel, pairs in PATCHES.items():
        path = source / rel
        original = path.read_text(encoding="utf-8")
        changed[path] = migrate(original, pairs, revert, rel)
    dst = source / "dist/licenses/DejaVu/LICENSE"
    bytes_ = license_file.read_bytes()
    if dst.exists() and dst.read_bytes() != bytes_:
        raise ValueError(f"Different DejaVu license exists: {dst}")
    # Apply only after all edits have passed preflight.
    for path, replacement in changed.items():
        if path.read_text(encoding="utf-8") != replacement:
            path.write_text(replacement, encoding="utf-8")
    if revert:
        if dst.exists():
            dst.unlink()
            if not any(dst.parent.iterdir()):
                dst.parent.rmdir()
    else:
        dst.parent.mkdir(parents=True, exist_ok=True)
        if not dst.exists():
            shutil.copyfile(license_file, dst)
    print("ZELDA_DEJAVU_FONT:", "REVERTED" if revert else "APPLIED", "(upstream 3692ba68; ABI 12)")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("source", type=Path)
    p.add_argument("--license", type=Path,
                   default=Path(__file__).resolve().parent.parent / "android/licenses/DejaVu-LICENSE.txt")
    p.add_argument("--revert", action="store_true")
    a = p.parse_args()
    run(a.source, a.license, a.revert)


if __name__ == "__main__":
    main()
