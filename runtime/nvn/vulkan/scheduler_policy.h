// GPU dependency classes; Vulkan-free policy, testable under ASAN/UBSAN.
#pragma once
#include <stdint.h>
typedef enum {
 VKSCHED_BEFORE_GRAPHICS, VKSCHED_BEFORE_COMPUTE,
 VKSCHED_BEFORE_TRANSFER, VKSCHED_UPLOAD_READY,
 VKSCHED_TRANSFER_TO_COMPUTE, VKSCHED_COMPUTE_TO_TRANSFER,
 VKSCHED_TRANSFER_TO_ALL, VKSCHED_COUNT
} VkSchedDependency;
enum {
 VKSCHED_STAGE_ALL=1u, VKSCHED_STAGE_GRAPHICS=2u,
 VKSCHED_STAGE_COMPUTE=4u, VKSCHED_STAGE_TRANSFER=8u,
 VKSCHED_READ=1u, VKSCHED_WRITE=2u, VKSCHED_TRANSFER_WRITE=4u
};
typedef struct {
 uint32_t src_stage,dst_stage,src_access,dst_access;
} VkSchedPolicy;
static inline VkSchedPolicy vk_sched_policy(VkSchedDependency dep) {
 const uint32_t rw=VKSCHED_READ|VKSCHED_WRITE;
 switch(dep) {
 case VKSCHED_BEFORE_GRAPHICS: return (VkSchedPolicy){VKSCHED_STAGE_ALL,VKSCHED_STAGE_GRAPHICS,VKSCHED_WRITE,rw};
 case VKSCHED_BEFORE_COMPUTE: return (VkSchedPolicy){VKSCHED_STAGE_ALL,VKSCHED_STAGE_COMPUTE,VKSCHED_WRITE,rw};
 case VKSCHED_BEFORE_TRANSFER: return (VkSchedPolicy){VKSCHED_STAGE_ALL,VKSCHED_STAGE_TRANSFER,VKSCHED_WRITE,rw};
 case VKSCHED_UPLOAD_READY: return (VkSchedPolicy){VKSCHED_STAGE_TRANSFER,VKSCHED_STAGE_ALL,VKSCHED_TRANSFER_WRITE,rw};
 case VKSCHED_TRANSFER_TO_COMPUTE: return (VkSchedPolicy){VKSCHED_STAGE_TRANSFER,VKSCHED_STAGE_COMPUTE,VKSCHED_TRANSFER_WRITE,rw};
 case VKSCHED_COMPUTE_TO_TRANSFER: return (VkSchedPolicy){VKSCHED_STAGE_COMPUTE,VKSCHED_STAGE_TRANSFER,VKSCHED_WRITE,rw};
 case VKSCHED_TRANSFER_TO_ALL: return (VkSchedPolicy){VKSCHED_STAGE_TRANSFER,VKSCHED_STAGE_ALL,VKSCHED_TRANSFER_WRITE,rw};
 default: return (VkSchedPolicy){VKSCHED_STAGE_ALL,VKSCHED_STAGE_ALL,VKSCHED_WRITE,rw};
 }
}
